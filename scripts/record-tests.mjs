// Turns the last Playwright run into src/config/tests.ts, so the site can show real numbers.
// Usage: npx playwright test && node scripts/record-tests.mjs
import { readFileSync, writeFileSync } from "node:fs";

const r = JSON.parse(readFileSync("e2e/.last-run.json", "utf8"));
const s = r.stats ?? {};
const out = `// Generated by scripts/record-tests.mjs from a real Playwright run. Do not edit by hand.
export const tests = {
  date: ${JSON.stringify(new Date().toISOString().slice(0, 10))},
  total: ${(s.expected ?? 0) + (s.unexpected ?? 0) + (s.flaky ?? 0)},
  passed: ${(s.expected ?? 0) + (s.flaky ?? 0)},
  failed: ${s.unexpected ?? 0},
  seconds: ${Math.round((s.duration ?? 0) / 1000)},
} as const;
`;
writeFileSync("src/config/tests.ts", out);
console.log(out);
