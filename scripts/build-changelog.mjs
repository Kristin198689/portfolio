// Builds src/config/changelog.ts from the real git history.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const raw = execSync("git log --no-merges --format=%H%x1f%ad%x1f%s --date=short", { encoding: "utf8" });
const entries = raw
  .trim()
  .split("\n")
  .filter(Boolean)
  .map((line) => {
    const [hash, date, subject] = line.split("\x1f");
    return { hash: hash.slice(0, 7), date, subject };
  });

const body = `// Generated by scripts/build-changelog.mjs from git log. Do not edit by hand.
export const changelog: Array<{ hash: string; date: string; subject: string }> = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync("src/config/changelog.ts", body);
console.log(`changelog: ${entries.length} commits`);
