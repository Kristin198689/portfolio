// Fetches the real GitHub contribution calendar of the last year with the GitHub CLI (it uses the
// local login, so no token is stored in the project) and writes src/config/contributions.ts.
// Only counts per day are saved, no repository names. Usage: node scripts/build-contributions.mjs
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const login = "Kristin198689";
const query = `query { user(login: "${login}") { contributionsCollection { contributionCalendar { totalContributions weeks { contributionDays { contributionCount date } } } } } }`;
const raw = execFileSync("gh", ["api", "graphql", "-f", `query=${query}`], { encoding: "utf8" });
const cal = JSON.parse(raw).data.user.contributionsCollection.contributionCalendar;
const weeks = cal.weeks.map((w) => w.contributionDays.map((d) => d.contributionCount));
const max = Math.max(...weeks.flat(), 1);
const level = (n) => (n === 0 ? 0 : n <= max * 0.25 ? 1 : n <= max * 0.5 ? 2 : n <= max * 0.75 ? 3 : 4);
const levels = weeks.map((w) => w.map(level));
const out = `// Generated by scripts/build-contributions.mjs from the GitHub API. Do not edit by hand.
export const contributions = {
  date: ${JSON.stringify(new Date().toISOString().slice(0, 10))},
  total: ${cal.totalContributions},
  // one array per week (Sunday first), each day a level from 0 to 4
  weeks: ${JSON.stringify(levels)} as ReadonlyArray<ReadonlyArray<number>>,
} as const;
`;
writeFileSync("src/config/contributions.ts", out);
console.log("total", cal.totalContributions, "weeks", weeks.length);
